  function getLang() { return current; }

  function setLang(lang) {
    if (LANGS.indexOf(lang) === -1) return false;
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    document.documentElement.setAttribute("lang", lang);
    return true;
  }

  function detect() {
    var stored = null;
    try { stored = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    if (stored && LANGS.indexOf(stored) !== -1) return stored;
    var nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
    return LANGS.indexOf(nav) !== -1 ? nav : "fr";
  }

  /* t("signup.done", {name:"X"}) — remplace {clé} par la valeur.
     Retourne la clé elle-même si absente : rend les oublis visibles. */
  function t(key, params) {
    var table = DICT[current] || DICT.fr;
    var s = table[key];
    if (s === undefined) s = DICT.fr[key];
    if (s === undefined) return key;
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.split("{" + k + "}").join(params[k]);
      });
    }
    return s;
  }

